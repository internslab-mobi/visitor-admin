package com.adminvisitor.auth.enums;

/**
 * Enumeration of authorization roles granted to authenticated users in the Visitor Management System.
 *
 * @author Logeshwaran
 */
public enum UserRole {

    /**
     * System Administrator role with full authority over user management, credentials, and configuration.
     */
    ADMIN,

    /**
     * Human Resources role with operational authorities within the system.
     */
    HR
}